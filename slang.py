EN = "qwertyuiop[]asdfghjkl;'zxcvbnm,."
RU = "йцукенгшщзхъфывапролджэячсмитьбю"
TO_RU = str.maketrans(EN, RU)
WORD = re.compile(r"[\wёЁ-]+|[^\w\s]+|\s+")
RU_LETTERS = re.compile(r"[а-яё]", re.I)


def fix_layout(text):
    """«ghbdtn rfr ltkf» → «привет как дела», если похоже на русский, набранный в английской раскладке."""
    t = (text or "").strip()
    if not t or RU_LETTERS.search(t) or not re.search(r"[a-z]", t, re.I) or "http" in t or "@" in t:
        return text
    words = re.findall(r"[a-z\[\];',.]+", t.lower())
    vowels_en = sum(sum(ch in "aeiouy" for ch in w) for w in words)
    letters = sum(len(w) for w in words)
    if letters < 4 or vowels_en / max(letters, 1) > 0.28:
        return text
    return t.lower().translate(TO_RU)


def normalize(text):
    t = fix_layout(text or "")
    out = []
    for tok in WORD.findall(t):
        low = tok.lower()
        out.append(WORDS[low] if low in WORDS else tok)
    return re.sub(r"\s{2,}", " ", "".join(out)).strip()
