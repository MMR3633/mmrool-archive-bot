EN = "qwertyuiop[]asdfghjkl;'zxcvbnm,."
RU = "йцукенгшщзхъфывапролджэячсмитьбю"
TO_RU = str.maketrans(EN, RU)
WORD = re.compile(r"[\wёЁ-]+|[^\w\s]+|\s+")
RU_LETTERS = re.compile(r"[а-яё]", re.I)


def fix_layout(text):
    """«ghbdtn rfr ltkf» → «привет как дела», если похоже на русский, набранный в английской раскладке."""
    t = (text or "").strip()
    if not t or RU_LETTERS.search(t) or not re.search(r"[a-z]", t, re.I) or "http" in t or "@" in t:
        return text
    words = re.findall(r"[a-z\[\];',.]+", t.lower())
    vowels_en = sum(sum(ch in "aeiouy" for ch in w) for w in words)
    letters = sum(len(w) for w in words)
    if letters < 4 or vowels_en / max(letters, 1) > 0.28:
        return text
    return t.lower().translate(TO_RU)


CHT_WHAT = {"такое", "это", "эт", "за", "там", "ты", "по", "с", "у", "значит", "случилось", "делать", "хочешь", "сказал"}


def normalize(text):
    """Сленг → обычные слова. «чт» у Расула чаще четверг, поэтому «что» только перед «такое/это/за…» или в начале вопроса."""
    t = fix_layout(text or "")
    toks = WORD.findall(t)
    words = [i for i, tok in enumerate(toks) if tok.strip() and re.match(r"[\wёЁ]", tok)]
    out = list(toks)
    for n, i in enumerate(words):
        low = toks[i].lower()
        if low == "чт":
            nxt = toks[words[n + 1]].lower() if n + 1 < len(words) else ""
            first = n == 0 and (t.rstrip().endswith("?") or nxt in CHT_WHAT)
            out[i] = "что" if nxt in CHT_WHAT or first else toks[i]
        elif low in WORDS:
            out[i] = WORDS[low]
    return re.sub(r"\s{2,}", " ", "".join(out)).strip()
